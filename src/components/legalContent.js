const localizeSections = (sections, lang) => {
  if (lang === 'en') return sections;
  const titleMap = sectionTitleMap[lang] || {};
  const lead = sectionLeadMap[lang] || '';
  return sections.map((section) => ({
    ...section,
    title: titleMap[section.title] || section.title,
    body: `${lead}${section.body}`,
  }));
};

export const getLegalPageContent = (type, lang) => {
  const safeLang = translations[lang] ? lang : 'en';
  const dictionary = translations[safeLang];
  const englishDictionary = translations.en;

  if (type === 'terms') {
    return {
      dictionary,
      title: dictionary.termsTitle || englishDictionary.termsTitle,
      subtitle: dictionary.termsSubtitle || englishDictionary.termsSubtitle,
      sections: localizeSections(termsSectionsEn, safeLang),
    };
  }

  return {
    dictionary,
    title: dictionary.privacyTitle || englishDictionary.privacyTitle,
    subtitle: dictionary.privacySubtitle || englishDictionary.privacySubtitle,
    sections: localizeSections(privacySectionsEn, safeLang),
  };
};
